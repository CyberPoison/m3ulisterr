// Starts an async duration probe (ffprobe reading just container metadata,
// not the whole file) and returns immediately - the caller can do other
// slow work (e.g. the AIOStreams subtitle lookup) before calling
// finishDurationProbe(), so the two run concurrently instead of back to
// back. Real duration is cached per source URL so repeat playlist loads
// don't reprobe at all.
function startDurationProbe($videoUrl, $ffprobePath) {
    // Bump whenever the shape of the cached result changes (new fields
    // added/removed) - otherwise a cache entry written under the OLD shape
    // keeps being served as-is for up to the full TTL, silently missing
    // whatever new field a caller now expects (this bit us directly: adding
    // width/height/colorTransfer/audio* fields without this left
    // subtitle_track_playlist.php reading them as empty from stale entries,
    // so RESOLUTION/VIDEO-RANGE quietly stopped appearing for any title
    // probed before the change, for up to 2 hours after deploy).
    $probeVersion = 3;

    $cacheFile = sys_get_temp_dir() . '/subtitle_track_duration_cache.json';
    $cacheKey = md5(stableCacheKeyForVideo($videoUrl) . '|v' . $probeVersion);

    $cache = [];
    if (file_exists($cacheFile)) {
        $decoded = json_decode((string) file_get_contents($cacheFile), true);
        if (is_array($decoded)) {
            $cache = $decoded;
        }
    }

    if (isset($cache[$cacheKey]) && (time() - $cache[$cacheKey]['time']) < 7200) {
        return ['cached' => $cache[$cacheKey]];
    }

    // bit_rate rides along with duration in the same probe (no extra network
    // round-trip) - it's what the RAM cache budget in
    // computeStreamCacheBudgetBytes() is sized from, so a high-bitrate
    // remux gets more cache headroom than a small 480p file automatically,
    // instead of every source getting the same fixed budget regardless of
    // how much data one segment of it actually holds. width/height/
    // color_transfer are what subtitle_track_playlist.php uses to add
    // RESOLUTION and VIDEO-RANGE to #EXT-X-STREAM-INF - without those,
    // strict HLS clients (Apple's AVFoundation - QuickTime, Safari, tvOS -
    // in particular) can fall back to assuming SDR for HDR10 (PQ) content,
    // which renders as a washed-out, wrong-hue image instead of failing
    // outright or tone-mapping correctly.
    // JSON, not the flat key=value format used elsewhere in this file -
    // needed here specifically because this probe (unlike the others) reads
    // fields from BOTH the video and audio streams at once, and JSON is what
    // keeps "width" from stream 0 unambiguous from an unrelated field on
    // stream 1 rather than everything collapsing into one flat, unordered
    // list of lines.
    // stream_tags=language,title rides along for the same reason bit_rate
    // does - no extra round trip - and is what lets the audio track actually
    // be CHOSEN by language instead of blindly taking 0:a:0. Real reports
    // that forced this: an "English" release of The Beekeeper whose first
    // audio track is Italian, and a Black Widow release whose first track is
    // Russian; both played in the wrong language while the playlist labelled
    // them English. See pickAudioStreamForLanguage().
    $probeCmd = [$ffprobePath, '-v', 'error', '-show_entries', 'format=duration,bit_rate:stream=index,codec_type,width,height,color_transfer,codec_name,channels,channel_layout,profile:stream_tags=language,title', '-of', 'json', $videoUrl];
    $descriptors = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'a']];
    $process = proc_open($probeCmd, $descriptors, $pipes);
    if (!is_resource($process)) {
        return ['cached' => false];
    }
    fclose($pipes[0]);
    stream_set_blocking($pipes[1], false);

    return ['cached' => null, 'process' => $process, 'pipes' => $pipes, 'cacheKey' => $cacheKey, 'cacheFile' => $cacheFile, 'videoUrl' => $videoUrl];
}

// Waits for (if needed) and returns ['duration' => float, 'bitRateBps' => int]
// from a handle started by startDurationProbe(), or false on failure. Safe
// to call immediately if the caller had no other work to interleave - it
// just blocks until ffprobe finishes, same as the old synchronous version
// did.
function finishDurationProbe($probe) {
    if ($probe['cached'] !== null) {
        return $probe['cached'] === false ? false : $probe['cached'];
    }

    $pipes = $probe['pipes'];
    $process = $probe['process'];

    $output = '';
    for ($waited = 0; $waited < 15; $waited++) {
        $read = [$pipes[1]];
        $write = null;
        $except = null;
        if (@stream_select($read, $write, $except, 1) > 0) {
            $output .= fread($pipes[1], 8192);
        }
        $status = proc_get_status($process);
        if (!$status['running'] && feof($pipes[1])) {
            break;
        }
    }
    fclose($pipes[1]);
    proc_terminate($process);
    proc_close($process);

    $decoded = json_decode(trim($output), true);
    if (!is_array($decoded)) {
        return false;
    }

    $duration = (float) ($decoded['format']['duration'] ?? 0);
    // ffprobe prints bit_rate as a numeric string, or omits/null's it
    // entirely for a container that doesn't carry one at all.
    $bitRateBps = (int) ($decoded['format']['bit_rate'] ?? 0);

    $width = 0;
    $height = 0;
    $colorTransfer = '';
    $audioCodecName = '';
    $audioChannels = 0;
    $audioChannelLayout = '';
    $audioProfile = '';
    // Every audio track, in ffmpeg's own 0:a:N order, so a caller can pick
    // one by language rather than being stuck with whichever happens to be
    // first in the file.
    $audioStreams = [];
    foreach ($decoded['streams'] ?? [] as $stream) {
        if (($stream['codec_type'] ?? '') === 'video' && $width === 0) {
            $width = (int) ($stream['width'] ?? 0);
            $height = (int) ($stream['height'] ?? 0);
            $colorTransfer = (string) ($stream['color_transfer'] ?? '');
        } elseif (($stream['codec_type'] ?? '') === 'audio') {
            if ($audioCodecName === '') {
                $audioCodecName = (string) ($stream['codec_name'] ?? '');
                $audioChannels = (int) ($stream['channels'] ?? 0);
                $audioChannelLayout = (string) ($stream['channel_layout'] ?? '');
                $audioProfile = (string) ($stream['profile'] ?? '');
            }
            $audioStreams[] = [
                'audioIndex' => count($audioStreams),
                'codecName' => (string) ($stream['codec_name'] ?? ''),
                'channels' => (int) ($stream['channels'] ?? 0),
                'channelLayout' => (string) ($stream['channel_layout'] ?? ''),
                'profile' => (string) ($stream['profile'] ?? ''),
                'language' => strtolower((string) ($stream['tags']['language'] ?? '')),
                'title' => (string) ($stream['tags']['title'] ?? ''),
            ];
        }
    }

    if ($duration <= 0) {
        return false;
    }

    // Some remuxes (this project deals with plenty of them) don't carry a
    // container-level bit_rate at all - ffprobe prints "N/A" for it, which
    // the regex above simply won't match, leaving bitRateBps at 0. Falling
    // back to a HEAD request's Content-Length gives a real per-title
    // estimate instead of falling through to computeStreamCacheBudgetBytes()'s
    // generic guess for every such file.
    if ($bitRateBps <= 0 && !empty($probe['videoUrl'])) {
        $ch = curl_init($probe['videoUrl']);
        curl_setopt($ch, CURLOPT_NOBODY, true);
        curl_setopt($ch, CURLOPT_HEADER, true);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_FOLLOWLOCATION, true);
        curl_setopt($ch, CURLOPT_TIMEOUT, 10);
        curl_setopt($ch, CURLOPT_SSL_VERIFYPEER, false);
        curl_setopt($ch, CURLOPT_SSL_VERIFYHOST, false);
        curl_exec($ch);
        $contentLength = (int) curl_getinfo($ch, CURLINFO_CONTENT_LENGTH_DOWNLOAD);
        curl_close($ch);
        if ($contentLength > 0) {
            $bitRateBps = (int) (($contentLength * 8) / $duration);
        }
    }

    $result = [
        'duration' => $duration,
        'bitRateBps' => $bitRateBps,
        'width' => $width,
        'height' => $height,
        'colorTransfer' => $colorTransfer,
        'audioCodecName' => $audioCodecName,
        'audioChannels' => $audioChannels,
        'audioChannelLayout' => $audioChannelLayout,
        'audioProfile' => $audioProfile,
        'audioStreams' => $audioStreams,
    ];

    $cache = [];
    if (file_exists($probe['cacheFile'])) {
        $decoded = json_decode((string) file_get_contents($probe['cacheFile']), true);
        if (is_array($decoded)) {
            $cache = $decoded;
        }
    }
    $cache[$probe['cacheKey']] = $result + ['time' => time()];
    @file_put_contents($probe['cacheFile'], json_encode($cache));

    return $result;
}

// Confirmed directly (probed the full keyframe list of a real 2h13m BluRay
// x264 source): keyframe spacing on real releases is NOT the tidy, regular
// 2-4s a naive fixed-length segmenter assumes - this file's gaps ranged from
// under 1s to over 10s, with roughly 1 in 10 keyframe gaps exceeding the 8s
// segment length subtitle_video_playlist.php/subtitle_audio_playlist.php
// used to cut on blindly. -c:v copy can only start a segment AT a keyframe
// (there's no decoding to trim mid-GOP), so any fixed nominal boundary that
// doesn't land on a real keyframe forces that segment to start from
// whichever keyframe came before it - which, when the gap is large, means
// the segment's first few seconds are content ALREADY shown by the previous
// segment (whose own -to cutoff reached right up to that same nominal
// boundary). That's a real, visible content repeat/rewind, not just a
// metadata problem - patching tfdt (see patchFirstFragmentTfdt()) fixes the
// container's timeline labeling but can't undo actual duplicated frames.
// The only real fix is cutting segments where the video's real keyframes
// actually are, the way every real HLS/CMAF packager (Shaka Packager,
// Bento4, Apple's own tools) already does - never blindly at a fixed
// interval.
//
function keyframeCacheFile() {
    return sys_get_temp_dir() . '/subtitle_track_keyframes_cache.json';
}

function keyframeCacheKey($videoUrl) {
    // Bump whenever computeKeyframeTimestamps()'s output shape/logic
    // changes - see startDurationProbe() for why this convention exists.
    $probeVersion = 1;
    return md5(stableCacheKeyForVideo($videoUrl) . '|v' . $probeVersion);
}

// Does the actual ffprobe work - reads packet-level keyframe flags only (no
// decoding). MP4's sample tables (stss = sync sample = keyframe list) live
// in the moov atom, so this is a metadata read, not a download of the whole
// file - but measured directly at 30-40s for a real 2+ hour movie anyway
// (the mov demuxer still has to walk the full sample table to answer a
// per-packet query, and -skip_frame nokey - which only emits keyframes -
// measured no faster, so the cost is inherent to the demuxer, not the
// output volume). That's far past what most HLS clients wait on a single
// playlist request before giving up - see getKeyframeTimestamps() for how
// callers avoid ever blocking on this directly.
function computeKeyframeTimestamps($videoUrl, $ffprobePath) {
    $probeCmd = [$ffprobePath, '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'packet=pts_time,flags', '-of', 'csv=p=0', $videoUrl];
    $descriptors = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'a']];
    $process = proc_open($probeCmd, $descriptors, $pipes);
    if (!is_resource($process)) {
        return [];
    }
    fclose($pipes[0]);

    $keyframes = [];
    while (($line = fgets($pipes[1])) !== false) {
        // csv=p=0 rows look like "13.888875,K__" - only the 'K' flag (first
        // character) marks a real sync sample/keyframe; everything else is
        // a regular packet that can't be a segment start under -c:v copy.
        $parts = explode(',', trim($line));
        if (count($parts) === 2 && isset($parts[1][0]) && $parts[1][0] === 'K') {
            $keyframes[] = (float) $parts[0];
        }
    }
    fclose($pipes[1]);
    proc_close($process);

    sort($keyframes, SORT_NUMERIC);

    // Every real segmenter needs a keyframe at (or before) time 0 to anchor
    // the very first segment - if the source's first packet somehow isn't
    // flagged as one (malformed/unusual encode), forcing a synthetic 0.0
    // entry is still correct: -ss 0 needs no seek at all, so segment 0 never
    // depends on this list being accurate at that specific point anyway.
    if (empty($keyframes) || $keyframes[0] > 0.001) {
        array_unshift($keyframes, 0.0);
    }

    return $keyframes;
}

// Same probe as computeKeyframeTimestamps(), but time-boxed: reads whatever
// keyframes it can within $timeoutSeconds, then terminates the process and
// returns what it has instead of waiting for the full 30-40s scan. Confirmed
// directly this demuxer processes a real movie at roughly 200x real-time
// (a 2h24m file's full scan took ~43s), so even a short bound like 5s
// typically covers a good 15-20+ minutes of real content - far more of the
// movie than most viewers reach before this source's background probe (see
// scheduleKeyframeProbe()) has had a chance to finish and warm the cache
// properly. Used to give a COLD-cache playlist request something much
// better than the plain fixed-length fallback without making it wait
// anywhere near as long as the full probe - see getKeyframeTimestampsForResponse()
// for how the two combine.
function computeKeyframeTimestampsBounded($videoUrl, $ffprobePath, $timeoutSeconds) {
    $probeCmd = [$ffprobePath, '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'packet=pts_time,flags', '-of', 'csv=p=0', $videoUrl];
    $descriptors = [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['file', '/dev/null', 'a']];
    $process = proc_open($probeCmd, $descriptors, $pipes);
    if (!is_resource($process)) {
        return [];
    }
    fclose($pipes[0]);
    stream_set_blocking($pipes[1], false);

    $keyframes = [];
    $buffer = '';
    $deadline = microtime(true) + $timeoutSeconds;

    while (microtime(true) < $deadline) {
        $status = proc_get_status($process);
        $read = [$pipes[1]];
        $write = null;
        $except = null;
        $remaining = max(0, $deadline - microtime(true));
        $usec = (int) min(200000, $remaining * 1000000);
        if (@stream_select($read, $write, $except, 0, $usec) > 0) {
            $chunk = fread($pipes[1], 65536);
            if ($chunk !== false && $chunk !== '') {
                $buffer .= $chunk;
                while (($pos = strpos($buffer, "\n")) !== false) {
                    $line = substr($buffer, 0, $pos);
                    $buffer = substr($buffer, $pos + 1);
                    $parts = explode(',', trim($line));
                    if (count($parts) === 2 && isset($parts[1][0]) && $parts[1][0] === 'K') {
                        $keyframes[] = (float) $parts[0];
                    }
                }
            }
        }
        if (!$status['running']) {
            break;
        }
    }

    $status = proc_get_status($process);
    if ($status['running']) {
        proc_terminate($process);
    }
    fclose($pipes[1]);
    proc_close($process);

    sort($keyframes, SORT_NUMERIC);
    if (empty($keyframes) || $keyframes[0] > 0.001) {
        array_unshift($keyframes, 0.0);
    }

    return $keyframes;
}

// Cache-first entry point for a PLAYLIST RESPONSE that needs keyframe data
// right now and can't wait through the full 30-40s probe. Returns
// [$keyframeTimes, $needsBackgroundProbe]:
// - Warm cache: the full list, $needsBackgroundProbe = false.
// - Cold cache: a bounded partial probe result (better than nothing, still
//   fast enough not to time out a real client), $needsBackgroundProbe =
//   true so the caller knows to follow up with scheduleKeyframeProbe()
//   AFTER sending its response, to complete and cache the full list for
//   next time - see the big comment on scheduleKeyframeProbe() for why
//   that step can never happen before the response goes out.
function getKeyframeTimestampsForResponse($videoUrl, $ffprobePath, $boundedSeconds = 5.0) {
    $keyframeTimes = getKeyframeTimestamps($videoUrl, $ffprobePath);
    if (!empty($keyframeTimes)) {
        return [$keyframeTimes, false];
    }

    return [computeKeyframeTimestampsBounded($videoUrl, $ffprobePath, $boundedSeconds), true];
}

function writeKeyframeCacheEntry($videoUrl, $keyframes) {
    $cacheFile = keyframeCacheFile();
    $cache = [];
    if (file_exists($cacheFile)) {
        $decoded = json_decode((string) file_get_contents($cacheFile), true);
        if (is_array($decoded)) {
            $cache = $decoded;
        }
    }
    $cache[keyframeCacheKey($videoUrl)] = ['keyframes' => $keyframes, 'time' => time()];
    @file_put_contents($cacheFile, json_encode($cache));
}

// NEVER runs the real probe before the response is sent - confirmed
// directly that doing so was the cause of a real, serious regression: a
// brand-new (never-before-cached) source's FIRST video/audio playlist
// request took 30-40s to respond while computeKeyframeTimestamps() ran
// synchronously, and that's long enough for a real player/HTTP client's own
// request timeout to fire first - the movie "never loads" from the
// viewer's side even though the server would eventually have answered.
// Keyframe-aligned segmentation is worth a lot (see
// buildKeyframeAlignedSegments()) but not at the cost of the playlist never
// being served at all.
//
// This is a pure cache read - a miss returns [] immediately, letting
// buildKeyframeAlignedSegments()'s existing fixed-length fallback take over
// for THIS request (worse - can repeat a little content at a boundary on a
// large-GOP source - but real and immediate). The caller is responsible for
// following up with scheduleKeyframeProbe() AFTER it has already sent its
// response (see that function for why), so that by the time the SAME
// viewer resumes/reloads, or the next viewer requests this title, the cache
// is warm and they get the fully keyframe-precise version instead.
//
// (An earlier version of this function tried to kick off the real probe as
// a detached background process - `exec('... &')` - right here, before
// responding. Confirmed directly that doesn't survive on this host: even a
// plain `nohup ... & disown` shelled out from PHP-FPM got killed the moment
// the request finished, so the "background" work never actually completed.
// fastcgi_finish_request(), which the caller uses instead, is the
// SAPI-level way to keep a worker process itself running past the point
// the client's response was flushed - reliable because it isn't relying on
// a child process surviving its parent's process group at all.)
function getKeyframeTimestamps($videoUrl, $ffprobePath) {
    $cacheFile = keyframeCacheFile();
    $cacheKey = keyframeCacheKey($videoUrl);

    if (file_exists($cacheFile)) {
        $decoded = json_decode((string) file_get_contents($cacheFile), true);
        if (is_array($decoded) && isset($decoded[$cacheKey]) && (time() - $decoded[$cacheKey]['time']) < 7200) {
            return $decoded[$cacheKey]['keyframes'];
        }
    }

    return [];
}

// Call AFTER the response has already been sent to the client (immediately
// following fastcgi_finish_request(), or as a fallback on a SAPI where
// that's unavailable - see below) whenever getKeyframeTimestamps() returned
// an empty/stale result for this source. Runs the real (slow) probe and
// writes it to cache so the NEXT request for this source gets the
// keyframe-precise segmentation - never the current one, which has already
// committed to the fixed-length fallback for its own response.
//
// A short-TTL lock file (much shorter than the cache's own 2-hour TTL) is
// what keeps the video AND audio playlist requests for the same just-gone-
// cold source - a real player fetches both within moments of each other -
// from each independently re-running this same 30-40s probe.
//
// On a SAPI without fastcgi_finish_request() (plain CLI, some non-FPM
// setups), this still runs synchronously before the calling script exits -
// slower for that one edge case, but correct, and every real deployment of
// this project runs under PHP-FPM anyway.
function scheduleKeyframeProbe($videoUrl, $ffprobePath) {
    $cacheKey = keyframeCacheKey($videoUrl);
    $lockFile = sys_get_temp_dir() . '/subtitle_track_keyframes_lock_' . $cacheKey . '.lock';
    if (file_exists($lockFile) && (time() - (int) @filemtime($lockFile)) < 120) {
        return;
    }
    @touch($lockFile);

    $keyframes = computeKeyframeTimestamps($videoUrl, $ffprobePath);
    if (!empty($keyframes)) {
        writeKeyframeCacheEntry($videoUrl, $keyframes);
    }
}

// Turns a sorted keyframe list into actual (start, length) segment pairs
// targeting roughly $targetSegmentLength each, but ALWAYS cutting exactly on
// a real keyframe - never in between. For each segment, picks the keyframe
// closest to (without exceeding) the target end; if the next available
// keyframe is already past the target (a GOP longer than the target itself -
// confirmed to happen on real sources, see getKeyframeTimestamps()), that
// keyframe is used anyway and the segment simply runs a bit long, since
// there's no earlier valid cut point under stream copy. Falls back to plain
// fixed-length segments if no keyframe list is available (e.g. probe
// failed) - worse (may repeat content at a boundary) but still playable,
// same as the pre-keyframe-aware behavior.
//
// The keyframe list is allowed to be PARTIAL - covering only the opening
// portion of the file, not all the way to $duration. That's not a
// malformed-input edge case to guard against defensively; it's an expected,
// everyday input shape (see computeKeyframeTimestampsBounded() - a
// deliberately time-boxed probe used so a brand-new source's first playlist
// request doesn't have to wait through the full 30-40s scan just to
// respond). Once the list runs dry noticeably before $duration, this
// switches to plain fixed-length stepping for the remainder - the same
// fallback quality as a source with no keyframe data at all, but only for
// the tail actually left unprobed, not the whole file. Getting this wrong
// (treating "list ran out" as "reached the real end of the file") would
// silently turn everything after the last known keyframe into ONE segment
// spanning the rest of the movie - confirmed directly as a real bug this
// exact function had before this comment was written.
function buildKeyframeAlignedSegments($keyframeTimes, $duration, $targetSegmentLength = 8) {
    if (empty($keyframeTimes)) {
        $segments = [];
        $numSegments = (int) ceil($duration / $targetSegmentLength);
        for ($i = 0; $i < $numSegments; $i++) {
            $start = $i * $targetSegmentLength;
            $segments[] = [$start, min($targetSegmentLength, $duration - $start)];
        }
        return $segments;
    }

    $segments = [];
    $current = 0.0;
    $count = count($keyframeTimes);
    $idx = 0;

    // Advance past any keyframes at/before 0 (there should be exactly the
    // one synthetic-or-real one at 0.0 itself).
    while ($idx < $count && $keyframeTimes[$idx] <= $current + 0.0001) {
        $idx++;
    }

    while ($current < $duration - 0.05) {
        // The list has run dry with real content still left uncovered - a
        // partial/bounded probe result, not a genuine end-of-file. Only a
        // small remaining tail (within about one target segment length of
        // $duration) is trusted as "this really is the end of the file";
        // anything larger switches to plain fixed-length stepping instead
        // of folding the entire unprobed remainder into one segment.
        if ($idx >= $count && ($duration - $current) > $targetSegmentLength * 1.5) {
            $end = min($current + $targetSegmentLength, $duration);
            $segments[] = [$current, $end - $current];
            $current = $end;
            continue;
        }

        $target = $current + $targetSegmentLength;
        $chosen = null;

        // Keep advancing while the NEXT keyframe is still within the target
        // window - $idx ends up at the first keyframe strictly beyond it.
        while ($idx < $count && $keyframeTimes[$idx] <= $target) {
            $chosen = $keyframeTimes[$idx];
            $idx++;
        }

        // No keyframe fell within the window at all - the current GOP
        // outlasts the target length, so the next real keyframe (however
        // far away) is the only valid place left to cut.
        if ($chosen === null) {
            if ($idx < $count) {
                $chosen = $keyframeTimes[$idx];
                $idx++;
            } else {
                $chosen = $duration;
            }
        }

        $end = min($chosen, $duration);
        if ($end <= $current) {
            // Guards against a malformed/duplicate keyframe list producing a
            // zero-or-negative-length segment - just reach the end instead
            // of looping forever.
            $end = $duration;
        }

        // Never emit a segment shorter than this - confirmed directly as a
        // real, reproducible bug: when two real keyframes land very close
        // together (here, the file's very first two keyframes were 0.083s
        // apart), the segment between them covers only 1-2 frames, and the
        // resulting fragment can come back small enough (well under 4KB) to
        // trip runFragmentedMp4Segment()'s "did ffmpeg actually produce
        // something real" sanity check - which exists to catch genuine
        // failures (ffmpeg dying, an empty response), not correctly-tiny
        // output, but can't tell the two apart from size alone. That
        // segment then 502s on every request for it, and since it's
        // segment 0 for a real title, the whole video/audio/subtitle
        // playlist fails to ever start - the movie "doesn't open" at all.
        // Merging forward into the next keyframe (or, if none give enough
        // length, straight to $duration) fixes it at the source: no segment
        // this pathologically short ever gets generated in the first place.
        $minSegmentLength = 1.0;
        while (($end - $current) < $minSegmentLength && $end < $duration) {
            if ($idx < $count) {
                $end = min($keyframeTimes[$idx], $duration);
                $idx++;
            } else {
                $end = $duration;
            }
        }

        $segments[] = [$current, $end - $current];
        $current = $end;
    }

    return $segments;
}

// Synchronous convenience wrapper for callers with no other work to
// interleave. Returns the duration in seconds, or false on failure - use
// getSourceDurationAndBitrate() instead when the bitrate is also needed.
function getSourceDuration($videoUrl, $ffprobePath) {
    $result = finishDurationProbe(startDurationProbe($videoUrl, $ffprobePath));
    return $result === false ? false : $result['duration'];
}

// Same probe, exposing the bitrate too - used to size the RAM cache budget
// per source (see computeStreamCacheBudgetBytes()).
function getSourceDurationAndBitrate($videoUrl, $ffprobePath) {
    return finishDurationProbe(startDurationProbe($videoUrl, $ffprobePath));
}

// The value handed to ffmpeg's -ss is deliberately NOT exactly $start -
// confirmed directly on a real BluRay MKV rip that landing precisely ON a
// keyframe's own timestamp is unreliable for -ss against Matroska sources:
// -ss values from a few milliseconds up to about 0.2s past the exact same
// keyframe all silently landed at the file's first keyframe (pts 0) instead
// of the intended one, while anything past roughly 0.2s landed correctly -
// an ffmpeg/Matroska seek-index quirk, not anything wrong with which
// keyframe was chosen. A small fixed margin comfortably clears that dead
// zone; it doesn't cost any real content because -c:v copy can only ever
// start a segment AT a keyframe regardless of the exact -ss value, so
// asking to land a bit past one still lands ON it, just via an approach
// distance the seek algorithm can resolve reliably - and the real absolute
// landing point is measured afterward anyway (see
// extractRealFragmentStartPtsTime()), so this only affects how reliably the
// intended keyframe is reached, never what timestamp ends up in the patched
// tfdt. Segment 0 needs no margin - -ss 0 is never ambiguous.
function seekTargetWithMargin($start) {
    return $start > 0 ? $start + 0.25 : 0;
}

// Tests whether an input-side -ss seek to $target (the SAME mechanism the
// real segment scripts use, no special recovery flags, including the same
// seekTargetWithMargin() clearance) actually lands near where it was asked
// to, using -copyts so the reported pts_time reflects the real source
// position instead of resetting near zero. Shared by isSeekReliable()'s two
// test points - see that function for why more than one point turned out to
// be necessary.
//
// Does NOT mux the seeked packets into any container - -f null discards
// them entirely, and the real landing pts_time is read straight out of
// -debug_ts's own stderr trace (the same technique
// extractRealFragmentStartPtsTime() already uses for the real segment
// scripts) instead of muxing to an intermediate file and re-probing it.
//
// Two earlier versions of this function both muxed to an intermediate file
// first, and BOTH turned out to have their own format-specific way of
// silently producing no readable output for a real AV1 source despite the
// seek itself working correctly:
// - MPEG-TS: ffmpeg muxes AV1 into it only as an unrecognized "private data
//   stream" (its own warning, verbatim) - ffprobe then reads back precisely
//   zero frames from it.
// - Plain (non-fragmented) MP4 with -copyts + -to: confirmed directly that
//   packets kept flowing through the demuxer (visible in -debug_ts) far
//   past where the seek landed, yet NONE of them ever reached the muxer -
//   "Output file is empty, nothing was encoded" - a separate AV1-specific
//   muxing gap, not a seek problem.
// Both failures were then indistinguishable from a genuinely broken seek
// index, and got the same fallback (a plain redirect, skipping HLS - and
// with it the subtitle track - entirely) meant for actually-corrupted
// sources. Reading the demuxer's own timestamp trace directly sidesteps
// the entire category of "can this codec even be muxed into the test
// format" bugs, since nothing gets muxed at all.
function testSeekLandsNear($target, $videoUrl, $ffmpegPath, $ffprobePath) {
    $probeCmd = [$ffmpegPath, '-y', '-debug_ts', '-copyts', '-ss', (string) seekTargetWithMargin($target), '-i', $videoUrl, '-to', (string) ($target + 10), '-map', '0:v:0', '-c:v', 'copy', '-f', 'null', '-'];
    $descriptors = [0 => ['pipe', 'r'], 1 => ['file', '/dev/null', 'a'], 2 => ['pipe', 'w']];
    $process = proc_open($probeCmd, $descriptors, $pipes);

    if (!is_resource($process)) {
        return false;
    }

    fclose($pipes[0]);
    $stderr = stream_get_contents($pipes[2]);
    fclose($pipes[2]);
    proc_close($process);

    $actualPts = extractRealFragmentStartPtsTime((string) $stderr, 'video');

    // Generous tolerance - keyframe snapping alone can legitimately land
    // several seconds before the requested target. This is about catching
    // "landed nowhere near what was asked for", not demanding exact
    // precision.
    return $actualPts !== null && $actualPts > 0 && abs($actualPts - $target) < 30;
}

// Some releases ship an MKV whose seek index is internally corrupted or
// incomplete - ffmpeg's own diagnosis for the classic case is literally
// "File is broken, keyframes not correctly marked!". For those files, an
// input-side -ss seek (exactly what the real segment scripts use) silently
// lands at roughly the same position regardless of the requested target,
// instead of erroring. The result: every segment ends up containing
// near-identical/overlapping content instead of continuing from the
// previous one - exactly the kind of jarring discontinuity that can crash a
// player right at the first segment boundary.
//
// Testing only ONE point well into the file (this function's original
// design) turned out to have a real, confirmed gap: a genuine Blu-ray MKV
// rip whose seek index covered the rest of the file perfectly (a seek to
// 1109s - past the 30%-of-duration test point - landed within a second of
// its target) still had -ss silently return pts=0 for EVERY position in
// roughly the first 10-20 seconds (confirmed directly: -ss 10 landed at 0,
// same as -ss 10.01, ruling out a formatting fluke). A check that only ever
// samples deep into the file can never see that - and HLS segmentation
// needs early-file seeks just as much as late ones (segment 1 starts
// wherever segment 0 ends, often well under 20s in). So this now tests TWO
// points - the original deep one, plus a fixed early one past typical
// intro/logo sequences but still inside where segment 1 or 2 would start -
// and requires BOTH to land correctly before trusting the source for HLS.
function isSeekReliable($videoUrl, $duration, $ffmpegPath, $ffprobePath) {
    // Bump this whenever the check's logic changes, so a code update can't
    // keep serving a stale verdict computed by the old (possibly buggy)
    // logic for up to the full cache TTL - it just naturally misses once and
    // recomputes under the new key instead.
    $checkVersion = 6;

    $cacheFile = sys_get_temp_dir() . '/subtitle_track_seek_check_cache.json';
    $cacheKey = md5(stableCacheKeyForVideo($videoUrl) . '|v' . $checkVersion);

    $cache = [];
    if (file_exists($cacheFile)) {
        $decoded = json_decode((string) file_get_contents($cacheFile), true);
        if (is_array($decoded)) {
            $cache = $decoded;
        }
    }

    if (isset($cache[$cacheKey]) && (time() - $cache[$cacheKey]['time']) < 7200) {
        return $cache[$cacheKey]['reliable'];
    }

    // Well past any intro/logo sequence, and proportionally into the file so
    // a long movie's index (if broken) doesn't get a pass just because the
    // test point happened to be early.
    $lateTarget = max(60, $duration * 0.3);
    $reliable = testSeekLandsNear($lateTarget, $videoUrl, $ffmpegPath, $ffprobePath);

    // Only worth the extra probe if the source is long enough for this
    // early point to be meaningfully distinct from the late one already
    // tested, and short files aren't where this failure mode has been seen
    // anyway.
    if ($reliable && $duration > 60) {
        $earlyTarget = 15.0;
        $reliable = testSeekLandsNear($earlyTarget, $videoUrl, $ffmpegPath, $ffprobePath);
    }

    $cache[$cacheKey] = ['reliable' => $reliable, 'time' => time()];
    @file_put_contents($cacheFile, json_encode($cache));

    return $reliable;
}
